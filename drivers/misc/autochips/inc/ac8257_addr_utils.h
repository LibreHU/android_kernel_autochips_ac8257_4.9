#ifndef AC8257_ADDR_UTILS_H
#define AC8257_ADDR_UTILS_H

// Note: only for 32 bits address conversion

#define  DEVADDR_M4U_BASE         0x40000000

#define  ARM2_DEVADDR_NOM4U_BASE  0x00000000
#define  ARM2_CPUADDR_BASE        0x20000000

#define  ARM1_DEVADDR_NOM4U_BASE  0x00000000 /* maybe 0x00000000 need to verify*/
#define  ARM1_CPUADDR_BASE        0x40000000

/*
Note:

ARM2_CPUADDR is phy addr for arm2 cpu;
since in arm2, pa and va is the same;
the addr after ARM2_DEVADDR_NOM4U_TO_CPUADDR/ARM1_CPUADDR_TO_ARM2_CPUADDR
can be used to do memcpy.

ARM1_CPUADDR is the phy addr for arm1 cpu.
eg:
    the addr for lk to load arm2.bin to. (0x4000 0000). for example, one variable in arm2.bin (like the resource of track image) is loaded at 0x4020 0000;
    in arm2, we access this variable using 0x0020 0000;
*/


#define  ARM1_DEVADDR_NOM4U_TO_M4U(DEVADDR_NOM4U)  \
	(((DEVADDR_NOM4U) - ARM1_DEVADDR_NOM4U_BASE) + DEVADDR_M4U_BASE)
#define  ARM1_DEVADDR_M4U_TO_NOM4U(DEVADDR_M4U) \
	(((DEVADDR_M4U) - DEVADDR_M4U_BASE) + ARM1_DEVADDR_NOM4U_BASE)

#define  ARM2_DEVADDR_NOM4U_TO_M4U(DEVADDR_NOM4U)  \
	(((DEVADDR_NOM4U)  - ARM2_DEVADDR_NOM4U_BASE) + DEVADDR_M4U_BASE)
#define  ARM2_DEVADDR_M4U_TO_NOM4U(DEVADDR_M4U)  \
	(((DEVADDR_M4U) - DEVADDR_M4U_BASE) + ARM2_DEVADDR_NOM4U_BASE)

#define  ARM1_DEVADDR_NOM4U_TO_CPUADDR(DEVADDR_NOM4U) \
	(((DEVADDR_NOM4U) - ARM1_DEVADDR_NOM4U_BASE) + ARM1_CPUADDR_BASE)
#define  ARM1_CPUADDR_TO_DEVADDR_NOM4U(ARM1_CPUADDR) \
	(((ARM1_CPUADDR) - ARM1_CPUADDR_BASE) + ARM1_DEVADDR_NOM4U_BASE)

#define  ARM2_DEVADDR_NOM4U_TO_CPUADDR(DEVADDR_NOM4U) \
	(((DEVADDR_NOM4U) - ARM2_DEVADDR_NOM4U_BASE) - ARM2_CPUADDR_BASE)
#define  ARM2_CPUADDR_TO_DEVADDR_NOM4U(ARM2_CPUADDR) \
	(((ARM2_CPUADDR) + ARM2_CPUADDR_BASE) + ARM2_DEVADDR_NOM4U_BASE)

#define  ARM2_DEVADDR_M4U_TO_CPUADDR(DEVADDR_M4U) \
	(((DEVADDR_M4U) - DEVADDR_M4U_BASE) - ARM2_CPUADDR_BASE)
#define  ARM2_CPUADDR_TO_DEVADDR_M4U(ARM2_CPUADDR) \
	(((ARM2_CPUADDR) + ARM2_CPUADDR_BASE) + DEVADDR_M4U_BASE)

#define  ARM1_CPUADDR_TO_ARM2_CPUADDR(ARM1_CPUADDR) \
	(((ARM1_CPUADDR) - ARM1_CPUADDR_BASE) - ARM2_CPUADDR_BASE)
#define  ARM2_CPUADDR_TO_ARM1_CPUADDR(ARM2_CPUADDR) \
	(((ARM2_CPUADDR) + ARM2_CPUADDR_BASE) + ARM1_CPUADDR_BASE)

#endif
