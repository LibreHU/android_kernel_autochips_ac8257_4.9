#define HAL_WRITE32(reg, value)		(*(volatile u32*)(reg) = (value))
#define HAL_READ32(reg)				(*(volatile u32*)(reg))

#define TVD_READ32(offset)			HAL_READ32((base + offset))
#define TVD_WRITE32(offset, value)	HAL_WRITE32((base + offset), (value))

#define TVD_SET_BIT(offset, TVD_BIT) \
	do { \
		u32 tv = TVD_READ32(offset); \
		tv |= (TVD_BIT); \
		TVD_WRITE32(offset, tv); \
	} while (0)

#define TVD_CLR_BIT(offset, TVD_BIT) \
	do { \
		u32 tv = TVD_READ32(offset); \
		tv &= (~(TVD_BIT)); \
		TVD_WRITE32(offset, tv); \
	} while (0)

#define TVD_SET_FIELD(offset, field, val) \
	do { \
		u32 tv = TVD_READ32(offset); \
		tv &= (~(field)); \
		tv |= (val); \
		TVD_WRITE32(offset, tv); \
	} while (0)

