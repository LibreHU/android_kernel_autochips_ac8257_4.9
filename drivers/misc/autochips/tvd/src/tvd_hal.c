void tvd_hal_irq_enable(int enable)
{
	void* base = _tvd_base;
	if (enable) {
		/*set TVD_BIT[0-1] to 0*/
		TVD_SET_FIELD(TVD_INTR_EN, (INTR_VPRES_TVD | INTR_MODE_TVD), 0x0);
	} else {
		/*set TVD_BIT[0-1] to 1*/
		TVD_SET_FIELD(TVD_INTR_EN, (INTR_VPRES_TVD | INTR_MODE_TVD), 0x3);
	}
}

void tvd_hal_vsync_irq_enable(int enable)
{
	void* base = _tvd_base;
	if (enable)
		TVD_CLR_BIT(TVD_INTR_EN, INTR_VSYNC_TVD);
	else
		TVD_SET_BIT(TVD_INTR_EN, INTR_VSYNC_TVD);
}

int  tvd_hal_irq_status(void)
{
	void* base = _tvd_base;
	u32 irqstatus = TVD_READ32(TVD_INTR_STA);
	u32 irqenable = (~(TVD_READ32(TVD_INTR_EN))) & (INTR_MODE_TVD | INTR_VPRES_TVD | INTR_VSYNC_TVD);
	irqstatus &= irqenable;
	tvd_info("the INTR_EN is 0x%X, INTR_STA is 0x%X, DFE_STA_00 is 0x%X\n",
			TVD_READ32(TVD_INTR_EN), TVD_READ32(TVD_INTR_STA), TVD_READ32(REG_DFE_STA_00));
	return irqstatus;
}

void tvd_hal_irq_clear(void)
{
	void* base = _tvd_base;
	TVD_WRITE32(TVD_INTR_STA, TVD_READ32(TVD_INTR_STA));
}

void tvd_hal_set_img_status(int enable)
{
	void* base = _vdisys_base;
	if (enable) {
		TVD_CLR_BIT((0x04), TVD_BIT(1));
	}
	else {
		TVD_SET_BIT((0x04), TVD_BIT(1));
	}
}

int  tvd_hal_vpres_on(void)
{
	void* base = _tvd_base;
	u32 dfe_sta = TVD_READ32(REG_DFE_STA_00);
	return ((dfe_sta & VPRES_ON) && (!(dfe_sta & VPRES_OFF)));
}

int  tvd_hal_sync_locked(int sel_ctg)
{
	void* base = _tvd_base;
	u32 reg = (sel_ctg ? REG_STA_CTG_01 : REG_TG_STA_00);
	u32 lock_status = (sel_ctg ? MODE_LOCK_STATUS : SIGNAL_LOCK_STATUS);
	u32 value = (TVD_READ32(reg) & lock_status);
	return (value == lock_status);
}

