/*
 * CVBS ANALOG ADC & PLL init
 * */
static void pllgp2_init(void)
{
	unsigned int tmp;

	tmp = HAL_READ32(_clk_base + 0x0b0);
	tmp &= (~(0xFF << 16));
	tmp |= (1 << 23) | (1 << 20) | (1 << 19) | (2 << 16);
	HAL_WRITE32(_clk_base + 0xb0, tmp);

	tmp = HAL_READ32(_clk_base + 0x0c0);
	tmp &= 0x8000001F;
	tmp |=  (1 << 30) |
			(1 << 27) |
			(1 << 26) |
			(1 << 23) |
			(1 << 22) |
			(2 << 19) |
			(1 << 18) |
			(1 << 15) |
			(1 << 14) |
			(1 << 10) |
			(1 << 9) |
			(1 << 5);
	HAL_WRITE32(_clk_base + 0x0c0, tmp);

	HAL_WRITE32(_vdisys_base + REG_VDISYS_CG_CLR0, 0xFFFFFFFF);

	HAL_WRITE32(_vdisys_base + REG_VDISYS_CVBS_ANAIF_CFG, 0xC0000000);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_BG_CFG0);
	tmp |= (1 << 0);
	HAL_WRITE32(_cvbs_base + REG_ANA_BG_CFG0, tmp);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBS_CFG1);
	tmp &= ~((IGEN_PWD_OFST) |
			(CVBS_PWD_OFST) |
			(CORE_PWD_OFST) |
			(CLAMP_PWD_OFST) |
			(INMUX_PWD_OFST) |
			(PGABUFNA_PWD_OFST) |
			(PROT_PWD_OFST) | 
			(SHIFTA_PWD_OFST) |
			(CVBSADC1_IO_PWD_OFST));
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBS_CFG1, tmp);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBS_CFG2);
	tmp &= ~((CVBSADC1_CORE_PWD_OFST) | (CVBSADC1_CK_PWD_OFST));
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBS_CFG2, tmp);

	DELAY_US(10);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBSPLL_CFG1);
	tmp |= 2;
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBSPLL_CFG1, tmp);

	DELAY_US(10);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBSPLL_CFG1);
	tmp &= ~(0x1);
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBSPLL_CFG1, tmp);

	DELAY_US(1);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBSPLL_CFG0);
	tmp |= (1 << 30) | (1 << 31);
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBSPLL_CFG0, tmp);

	DELAY_US(10);
}

/*
 * CVBS ANALOG ADC & PLL deinit
 * */
static void pllgp2_deinit(void)
{
	unsigned int tmp;

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBSPLL_CFG0);
	tmp &= ~((1 << 30) | (1 << 31));
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBSPLL_CFG0, tmp);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBSPLL_CFG1);
	tmp &= ~(0x2);
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBSPLL_CFG1, tmp);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBS_CFG2);
	tmp |= ((CVBSADC1_CORE_PWD_OFST) | (CVBSADC1_CK_PWD_OFST));
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBS_CFG2, tmp);

	tmp = HAL_READ32(_cvbs_base + REG_ANA_CVBS_CFG1);
	tmp |=  ((IGEN_PWD_OFST) |
			(CVBS_PWD_OFST) |
			(CORE_PWD_OFST) |
			(CLAMP_PWD_OFST) |
			(INMUX_PWD_OFST) |
			(PGABUFNA_PWD_OFST) |
			(PROT_PWD_OFST) |
			(SHIFTA_PWD_OFST) |
			(CVBSADC1_IO_PWD_OFST));
	HAL_WRITE32(_cvbs_base + REG_ANA_CVBS_CFG1, tmp);

	HAL_WRITE32(_vdisys_base + REG_VDISYS_CVBS_ANAIF_CFG, 0x00000000);

	tmp = HAL_READ32(_clk_base + 0x0c0);
	tmp &= ~(1 << 26);
	HAL_WRITE32(_clk_base + 0x0c0, tmp);
	tvd_info("CLK_0xC0 = %08X\n", tmp);

	tmp = HAL_READ32(_clk_base + 0x0b0);
	tmp &= ~(1 << 19);
	HAL_WRITE32(_clk_base + 0xb0, tmp);
}

#define CLK_DBG_CFG		(0x10C)
#define CLK_MISC_CFG_0	(0x104)
#define CLK26CALI_0		(0x220)
#define CLK26CALI_1		(0x224)
static unsigned int mt_get_ckgen_freq(unsigned int ID)
{
	int output = 0, i = 0;
	unsigned int temp, clk26cali_0, clk_dbg_cfg, clk_misc_cfg_0, clk26cali_1;

	clk_dbg_cfg = HAL_READ32(_clk_base + CLK_DBG_CFG);
	HAL_WRITE32(_clk_base + CLK_DBG_CFG, (clk_dbg_cfg & 0xFFFFC0FC)|(ID << 8)|(0x1)); //sel ckgen_cksw[22] and enable freq meter sel ckgen[21:16], 01:hd_faxi_ck

	clk_misc_cfg_0 = HAL_READ32(_clk_base + CLK_MISC_CFG_0);
	HAL_WRITE32(_clk_base + CLK_MISC_CFG_0, (clk_misc_cfg_0 & 0x00FFFFFF)); // select divider?dvt set zero
	clk26cali_0 = HAL_READ32(_clk_base + CLK26CALI_0);
	clk26cali_1 = HAL_READ32(_clk_base + CLK26CALI_1);
	HAL_WRITE32(_clk_base + CLK26CALI_0, 0x1000);
	HAL_WRITE32(_clk_base + CLK26CALI_0, 0x1010);

	/* wait frequency meter finish */
	while (HAL_READ32(_clk_base + CLK26CALI_0) & 0x10)
	{
		DELAY_MS(10);
		i++;
		if(i > 10)
			break;
	}

	temp = HAL_READ32(_clk_base + CLK26CALI_1) & 0xFFFF;

	output = ((temp * 26000) ) / 1024; // Khz

	HAL_WRITE32(_clk_base + CLK_DBG_CFG, clk_dbg_cfg);
	HAL_WRITE32(_clk_base + CLK_MISC_CFG_0, clk_misc_cfg_0);
	HAL_WRITE32(_clk_base + CLK26CALI_0, clk26cali_0);
	HAL_WRITE32(_clk_base + CLK26CALI_1, clk26cali_1);

	//print("ckgen meter[%d] = %d Khz\n", ID, output);
	return output;

}

static void cvbs_select_port(int enable)
{
	void *base = _cvbs_base;
	if (enable) {
		/*select port & channel*/
		TVD_SET_BIT(REG_ANA_CVBS_CFG0, RG_BLANK_EN);
		TVD_SET_FIELD(REG_ANA_CVBS_CFG0, RG_AISEL, (0x1 << 24));
		TVD_CLR_BIT(REG_ANA_CVBS_CFG0, TVD_BIT(22));
		TVD_SET_FIELD(REG_ANA_CVBS_CFG1, (3 << 16), (1 << 16));
		TVD_SET_BIT(REG_ANA_CVBS_CFG2, TVD_BIT(28));
		TVD_CLR_BIT(REG_ANA_CVBS_CFG2, TVD_BIT(26));
	} else {
		/*disable select port & channel*/
		TVD_CLR_BIT(REG_ANA_CVBS_CFG0, RG_BLANK_EN);
		TVD_SET_FIELD(REG_ANA_CVBS_CFG0, RG_AISEL, (0x0 << 24));
	}
}

static void tvd_clock_on(void)
{
	void *base = _clk_base;
	unsigned int tz = 0;
	pllgp2_init();
	tz = mt_get_ckgen_freq(0x24);
	tvd_info("tvd_ck = %uKHz\n", tz);
	/*enable cvbs clock which is to set 10005e50 TVD_BIT[6] = 1*/
	//TVD_SET_BIT((0x00), TVD_BIT(6)); //AC8227L
	TVD_SET_FIELD((0xC0), (3 << 23), (1 << 23)); //0:clk26m 1:cvbspll_108d2 2:syspll3_d4
	TVD_CLR_BIT((0xC0), TVD_BIT(25)); //AC8257
	TVD_SET_BIT((0xC0), TVD_BIT(26)); //AC8257
	cvbs_select_port(1);
}

static void tvd_clock_off(void)
{
	void *base = _clk_base;
	cvbs_select_port(0);
	/*disable cvbs clock*/
	TVD_CLR_BIT((0xC0), TVD_BIT(26));
	pllgp2_deinit();
}

